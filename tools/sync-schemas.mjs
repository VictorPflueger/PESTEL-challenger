#!/usr/bin/env node
// Writes js/schemas.js from schemas/*.json, because the page cannot load a JSON file under its security
// policy (PLAN.md P14) and reads this module instead. SCHEMAS holds every schema by its file name, as
// js/schema.js resolves "$ref": "decision.json". REQUESTS holds the format of each agent's request with
// every $ref written out and $schema, $id and title left out, as output_config.format and the Scout's
// tool take it.
//   node tools/sync-schemas.mjs           write js/schemas.js
//   node tools/sync-schemas.mjs --check   fail if js/schemas.js differs from the JSON
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "schemas");
const OUT = path.join(ROOT, "js", "schemas.js");
const read = (file) => JSON.parse(readFileSync(file, "utf8"));
const base = (file) => path.basename(file, ".json");

const schemas = Object.fromEntries(readdirSync(DIR).filter((f) => f.endsWith(".json")).sort().map((f) => [base(f), read(path.join(DIR, f))]));

/**
 * A request schema with every $ref replaced by its target, and no $schema, $id or title keyword anywhere.
 * A field named "title" inside properties is a field, not the keyword, and stays.
 */
function inline(node, from) {
  if (Array.isArray(node)) return node.map((n) => inline(n, from));
  if (!node || typeof node !== "object") return node;
  if (node.$ref) {
    const target = path.resolve(from, node.$ref);
    const name = base(target);
    if (!schemas[name]) throw new Error(`unknown $ref ${node.$ref} in ${from}`);
    const { $ref, ...rest } = node;
    return inline({ ...schemas[name], ...rest }, path.dirname(target));
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (["$schema", "$id", "title"].includes(k)) continue;
    out[k] = k === "properties" ? Object.fromEntries(Object.entries(v).map(([p, sub]) => [p, inline(sub, from)])) : inline(v, from);
  }
  return out;
}
const requestDir = path.join(DIR, "requests");
const requests = Object.fromEntries(readdirSync(requestDir).filter((f) => f.endsWith(".json")).sort().map((f) => {
  const schema = read(path.join(requestDir, f));
  return [schema.title, inline(schema, requestDir)];
}));

const text = `// Generated by tools/sync-schemas.mjs from schemas/*.json. Do not edit: change the JSON and run the tool;
// tests/schemas.mjs fails while the two differ.
export const SCHEMAS = ${JSON.stringify(schemas, null, 2)};

export const REQUESTS = ${JSON.stringify(requests, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("js/schemas.js differs from schemas/*.json: run node tools/sync-schemas.mjs");
    process.exit(1);
  }
  console.log(`js/schemas.js matches ${Object.keys(schemas).length} schemas and ${Object.keys(requests).length} request formats.`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote js/schemas.js: ${Object.keys(schemas).length} schemas, ${Object.keys(requests).length} request formats.`);
}
